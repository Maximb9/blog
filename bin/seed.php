$insertArticle = $pdo->prepare(
    'INSERT INTO articles (title, description, content, image, views, published_at)
     VALUES (:title, :description, :content, :image, :views, :published_at)'
);

$insertLink = $pdo->prepare(
    'INSERT INTO article_categories (article_id, category_id) VALUES (:article_id, :category_id)'
);

foreach ($articles as $article) {
    $categoryIndexes = $article['categories'];
    unset($article['categories']);

    $insertArticle->execute($article);
    $articleId = (int)$pdo->lastInsertId();

    foreach ($categoryIndexes as $categoryIndex) {
        $insertLink->execute([
            'article_id' => $articleId,
            'category_id' => $categoryIds[$categoryIndex],
        ]);
    }
}
